import {build} from 'esbuild';
import vm from 'node:vm';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const dir=new URL('.',import.meta.url);
const bundled=await build({entryPoints:[new URL('app.js',dir).pathname],bundle:true,write:false,format:'iife',target:'es2022',minify:true,legalComments:'none'});
const script=bundled.outputFiles[0].text.replaceAll('</script','<\\/script');
const html=(await readFile(new URL('index.html',dir),'utf8')).replace('/*__APP_SCRIPT__*/',()=>script);
new vm.Script(html.match(/<script type="module">([\s\S]*?)<\/script>/)[1]);
await writeFile(new URL('../../src/workbench-html.ts',dir),'// Generated by apps/workbench/build.mjs. Do not edit manually.\nexport const WORKBENCH_HTML = '+JSON.stringify(html)+';\n');
await mkdir(new URL('dist/',dir),{recursive:true});
await writeFile(new URL('dist/workbench.html',dir),html);
console.log('Built self-contained MCP App: '+Buffer.byteLength(html)+' bytes');
