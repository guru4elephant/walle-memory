// Run with playwright-cli run-code --filename=walle-memory-worker/test/ui-flow.js
// Requires test/ui-server.mjs; every credential is a disposable fixture value.
async page => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const uiErrors = [];
  page.on('pageerror', error => uiErrors.push(error.message));
  await page.locator('#registration-note').getByText('管理员', { exact: false }).waitFor();
  ensure(await page.locator('#auth-toggle').isHidden(), 'Public registration must be hidden');
  await page.locator('#admin-details summary').click();
  await page.locator('#admin-key').fill('local-ui-test-admin');
  await page.locator('#admin-name').fill('Browser Test');
  await page.locator('#admin-email').fill('browser-test@example.invalid');
  await page.locator('#admin-password').fill('temporary-browser-password');
  await page.locator('#admin-create').click();
  await page.locator('#admin-account-status').getByText('账号已创建', { exact: false }).waitFor();
  ensure(await page.locator('#admin-key').inputValue() === '', 'Administrator secret must be cleared');
  ensure(await page.locator('#admin-password').inputValue() === '', 'Password must be cleared');
  await page.locator('#admin-key').fill('local-ui-test-admin');
  await page.locator('#admin-load').click();
  await page.locator('#admin-status').getByText('已加载', { exact: false }).waitFor();
  await page.locator('#admin-tenants button').filter({ hasText: 'Legacy test memories' }).click();
  await page.locator('#claim-name').fill('旧记忆');
  await page.locator('#claim-type').fill('semantic');
  await page.locator('#admin-key').fill('local-ui-test-admin');
  await page.locator('#admin-claim').click();
  await page.locator('#admin-claim-status').getByText('已绑定空间', { exact: false }).waitFor();
  await page.locator('#admin-details summary').click();
  await page.locator('#auth-email').fill('browser-test@example.invalid');
  await page.locator('#auth-password').fill('temporary-browser-password');
  await page.locator('#auth-submit').click();
  await page.locator('#account-name').getByText('Browser Test').waitFor();
  await page.locator('#space-list button').filter({ hasText: '旧记忆' }).waitFor();
  await page.locator('#space-name').fill('工作知识');
  await page.locator('#space-type').fill('semantic');
  await page.locator('#space-submit').click();
  await page.locator('#selected-space-name').getByText('工作知识').waitFor();
  await page.locator('#key-label').fill('Temporary browser key');
  const issuance = page.waitForResponse(response => response.url().endsWith('/keys') && response.request().method() === 'POST');
  await page.locator('#key-submit').click();
  const response = await issuance;
  ensure(response.status() === 201, 'Key creation must succeed');
  let credential = (await response.json()).api_key;
  await page.locator('#secret-dialog').waitFor({ state: 'visible' });
  ensure(await page.locator('#secret-output').inputValue() === credential, 'One-time key should be shown');
  ensure(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'Secrets must not enter browser storage');
  await page.locator('#close-secret').click();
  ensure(await page.locator('#secret-output').inputValue() === '', 'Closing key dialog must clear it');
  const base = new URL(page.url()).origin;
  const write = await page.request.post(base + '/memory/browser-note', {
    headers: { 'X-Api-Key': credential }, data: { value: 'temporary UI proof', description: 'browser regression proof' },
  });
  ensure(write.status() === 200, 'Scoped key can write memory');
  ensure((await page.request.get(base + '/memory/browser-note', { headers: { 'X-Api-Key': credential } })).status() === 200, 'Scoped key can read memory');
  await page.locator('#key-list button').filter({ hasText: '撤销' }).click();
  await page.locator('#confirm-action').click();
  await page.locator('#key-list').getByText('已撤销', { exact: true }).waitFor();
  ensure((await page.request.get(base + '/memory/browser-note', { headers: { 'X-Api-Key': credential } })).status() === 401, 'Revoked key must fail');
  credential = '';
  await page.locator('#space-name').fill('生活事件');
  await page.locator('#space-type').fill('episodic');
  await page.locator('#space-submit').click();
  await page.locator('#selected-space-name').getByText('生活事件').waitFor();
  await page.locator('#space-list button').filter({ hasText: '工作知识' }).click();
  await page.locator('#selected-space-name').getByText('工作知识').waitFor();
  await page.locator('#key-list').getByText('已撤销', { exact: true }).waitFor();
  ensure(uiErrors.length === 0, 'No unhandled browser JavaScript errors');
  await page.screenshot({ path: 'validation/account-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow');
  await page.screenshot({ path: 'validation/account-mobile.png' });
  await page.locator('#key-form').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'validation/account-mobile-keys.png' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('#logout').click();
  await page.locator('#auth-section').waitFor({ state: 'visible' });
  ensure(await page.locator('#secret-output').inputValue() === '', 'Logout must clear key');
  ensure((await page.request.get(base + '/auth/me')).status() === 401, 'Logout invalidates the server session');
  return { passed: true, flows: ['admin account creation', 'legacy claim', 'login', 'space creation and switching', 'scoped key issue and clear', 'memory access', 'key revocation', 'logout'], desktop: true, mobile: true, javascriptErrors: uiErrors.length };
}
